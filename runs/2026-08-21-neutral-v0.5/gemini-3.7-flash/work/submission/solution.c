static inline void process_station(ThreadData *td, __m256i masked, int len, int temp) {
    __m128i low128 = _mm256_castsi256_si128(masked);
    uint64_t w0 = (uint64_t)_mm_cvtsi128_si64(low128);
    uint64_t w1 = (uint64_t)_mm_extract_epi64(low128, 1);
    uint64_t h = _mm_crc32_u64(0, w0 ^ w1 ^ (uint64_t)len);
    int idx = (int)(h & TABLE_MASK);

    while (1) {
        HashEntry *e = &td->table[idx];
        if (__builtin_expect(e->count == 0, 0)) {
            e->vec = masked;
            e->len = len;
            e->min = temp;
            e->max = temp;
            e->sum = temp;
            e->count = 1;
            td->count++;
            return;
        }
        __m256i diff = _mm256_xor_si256(masked, e->vec);
        if (__builtin_expect(_mm256_testz_si256(diff, diff) && e->len == len, 1)) {
            if (temp < e->min) e->min = temp;
            if (temp > e->max) e->max = temp;
            e->sum += temp;
            e->count++;
            return;
        }
        idx = (idx + 1) & TABLE_MASK;
    }
}

static inline int parse_temp_inline(const char *p, const char **next_ptr) {
    int neg = (*p == '-');
    p += neg;
    int temp;
    if (p[1] == '.') {
        temp = (p[0] - '0') * 10 + (p[2] - '0');
        *next_ptr = p + 4;
    } else {
        temp = (p[0] - '0') * 100 + (p[1] - '0') * 10 + (p[3] - '0');
        *next_ptr = p + 5;
    }
    return neg ? -temp : temp;
}

static inline const char *drain_ptr(ThreadData *td, const char *p, const char *end, const char *file_end, const __m256i semi_vec) {
    while (p < end && p < file_end) {
        if (__builtin_expect(p + 32 <= file_end, 1)) {
            __m256i raw = _mm256_loadu_si256((const __m256i *)p);
            __m256i cmp = _mm256_cmpeq_epi8(raw, semi_vec);
            int mask = _mm256_movemask_epi8(cmp);
            if (__builtin_expect(mask != 0, 1)) {
                int len = __builtin_ctz(mask);
                __m256i masked = _mm256_and_si256(raw, _mm256_load_si256((const __m256i *)MASK_TABLE[len]));
                const char *next;
                int temp = parse_temp_inline(p + len + 1, &next);
                process_station(td, masked, len, temp);
                p = next;
                continue;
            }
        }
        const char *semi = memchr(p, ';', file_end - p);
        if (!semi) break;
        int len = semi - p;
        uint8_t buf[32] = {0};
        memcpy(buf, p, len < 32 ? len : 32);
        __m256i masked = _mm256_loadu_si256((const __m256i *)buf);
        const char *next;
        int temp = parse_temp_inline(semi + 1, &next);
        process_station(td, masked, len, temp);
        p = next;
    }
    return p;
}

static void *worker_thread(void *arg) {
    ThreadArg *targ = (ThreadArg *)arg;
    if (targ->cpu_id >= 0) {
        cpu_set_t cpuset;
        CPU_ZERO(&cpuset);
        CPU_SET(targ->cpu_id, &cpuset);
        pthread_setaffinity_np(pthread_self(), sizeof(cpu_set_t), &cpuset);
    }

    const char *data = targ->data;
    size_t start = targ->start;
    size_t end = targ->end;
    size_t total_size = targ->total_size;
    const char *file_end = data + total_size;
    ThreadData *td = targ->td;

    const __m256i semi_vec = _mm256_set1_epi8(';');

    size_t len = end - start;
    size_t s0 = start;
    size_t s1 = start + len / 4;
    size_t s2 = start + len / 2;
    size_t s3 = start + (3 * len) / 4;

    while (s1 < end && data[s1 - 1] != '\n') s1++;
    while (s2 < end && data[s2 - 1] != '\n') s2++;
    while (s3 < end && data[s3 - 1] != '\n') s3++;

    const char *p0 = data + s0;
    const char *end0 = data + s1;
    const char *p1 = data + s1;
    const char *end1 = data + s2;
    const char *p2 = data + s2;
    const char *end2 = data + s3;
    const char *p3 = data + s3;
    const char *end3 = data + end;

    while (p0 < end0 && p1 < end1 && p2 < end2 && p3 < end3 &&
           p0 + 32 <= file_end && p1 + 32 <= file_end && p2 + 32 <= file_end && p3 + 32 <= file_end) {

        __m256i raw0 = _mm256_loadu_si256((const __m256i *)p0);
        __m256i raw1 = _mm256_loadu_si256((const __m256i *)p1);
        __m256i raw2 = _mm256_loadu_si256((const __m256i *)p2);
        __m256i raw3 = _mm256_loadu_si256((const __m256i *)p3);

        __m256i cmp0 = _mm256_cmpeq_epi8(raw0, semi_vec);
        __m256i cmp1 = _mm256_cmpeq_epi8(raw1, semi_vec);
        __m256i cmp2 = _mm256_cmpeq_epi8(raw2, semi_vec);
        __m256i cmp3 = _mm256_cmpeq_epi8(raw3, semi_vec);

        int mask0 = _mm256_movemask_epi8(cmp0);
        int mask1 = _mm256_movemask_epi8(cmp1);
        int mask2 = _mm256_movemask_epi8(cmp2);
        int mask3 = _mm256_movemask_epi8(cmp3);

        if (__builtin_expect(mask0 != 0 && mask1 != 0 && mask2 != 0 && mask3 != 0, 1)) {
            int len0 = __builtin_ctz(mask0);
            int len1 = __builtin_ctz(mask1);
            int len2 = __builtin_ctz(mask2);
            int len3 = __builtin_ctz(mask3);

            __m256i masked0 = _mm256_and_si256(raw0, _mm256_load_si256((const __m256i *)MASK_TABLE[len0]));
            __m256i masked1 = _mm256_and_si256(raw1, _mm256_load_si256((const __m256i *)MASK_TABLE[len1]));
            __m256i masked2 = _mm256_and_si256(raw2, _mm256_load_si256((const __m256i *)MASK_TABLE[len2]));
            __m256i masked3 = _mm256_and_si256(raw3, _mm256_load_si256((const __m256i *)MASK_TABLE[len3]));

            const char *next0;
            const char *next1;
            const char *next2;
            const char *next3;

            int temp0 = parse_temp_inline(p0 + len0 + 1, &next0);
            int temp1 = parse_temp_inline(p1 + len1 + 1, &next1);
            int temp2 = parse_temp_inline(p2 + len2 + 1, &next2);
            int temp3 = parse_temp_inline(p3 + len3 + 1, &next3);

            process_station(td, masked0, len0, temp0);
            process_station(td, masked1, len1, temp1);
            process_station(td, masked2, len2, temp2);
            process_station(td, masked3, len3, temp3);

            p0 = next0;
            p1 = next1;
            p2 = next2;
            p3 = next3;
        } else {
            p0 = drain_ptr(td, p0, p0 + 1, file_end, semi_vec);
            p1 = drain_ptr(td, p1, p1 + 1, file_end, semi_vec);
            p2 = drain_ptr(td, p2, p2 + 1, file_end, semi_vec);
            p3 = drain_ptr(td, p3, p3 + 1, file_end, semi_vec);
        }
    }

    drain_ptr(td, p0, end0, file_end, semi_vec);
    drain_ptr(td, p1, end1, file_end, semi_vec);
    drain_ptr(td, p2, end2, file_end, semi_vec);
    drain_ptr(td, p3, end3, file_end, semi_vec);

    return NULL;
}

typedef struct {
    char name[64];
    int len;
    int min;
    int max;
    int64_t sum;
    int64_t count;
} MergedStation;

static int compare_merged(const void *a, const void *b) {
    const MergedStation *sa = (const MergedStation *)a;
    const MergedStation *sb = (const MergedStation *)b;
    return strcmp(sa->name, sb->name);
}

static char *format_fixed_1(char *p, int val) {
    if (val < 0) {
        *p++ = '-';
        val = -val;
    }
    int int_part = val / 10;
    int frac_part = val % 10;
    if (int_part >= 100) {
        *p++ = '0' + (int_part / 100);
        int_part %= 100;
        *p++ = '0' + (int_part / 10);
        *p++ = '0' + (int_part % 10);
    } else if (int_part >= 10) {
        *p++ = '0' + (int_part / 10);
        *p++ = '0' + (int_part % 10);
    } else {
        *p++ = '0' + int_part;
    }
    *p++ = '.';
    *p++ = '0' + frac_part;
    return p;
}

int main(int argc, char **argv) {
    if (argc < 2) return 1;

    int fd = open(argv[1], O_RDONLY);
    if (fd < 0) return 1;

    struct stat st;
    if (fstat(fd, &st) < 0 || st.st_size == 0) {
        close(fd);
        printf("{}\n");
        return 0;
    }

    size_t file_size = st.st_size;
    const char *data = (const char *)mmap(NULL, file_size, PROT_READ, MAP_SHARED, fd, 0);
    if (data == MAP_FAILED) {
        close(fd);
        return 1;
    }
    madvise((void *)data, file_size, MADV_SEQUENTIAL | MADV_HUGEPAGE);

    int num_threads = 6;
    if (file_size < 1000000) num_threads = 1;

    pthread_t threads[num_threads];
    ThreadArg args[num_threads];
    ThreadData tdata[num_threads];
    memset(tdata, 0, sizeof(tdata));

    size_t chunk_size = file_size / num_threads;

    for (int i = 0; i < num_threads; i++) {
        size_t start = (i == 0) ? 0 : i * chunk_size;
        if (i > 0) {
            while (start < file_size && data[start - 1] != '\n') {
                start++;
            }
        }
        size_t end = (i == num_threads - 1) ? file_size : (i + 1) * chunk_size;
        if (i < num_threads - 1) {
            while (end < file_size && data[end - 1] != '\n') {
                end++;
            }
        }

        args[i].data = data;
        args[i].start = start;
        args[i].end = end;
        args[i].total_size = file_size;
        args[i].td = &tdata[i];
        args[i].cpu_id = i;

        if (i > 0) {
            pthread_create(&threads[i], NULL, worker_thread, &args[i]);
        }
    }

    worker_thread(&args[0]);

    for (int i = 1; i < num_threads; i++) {
        pthread_join(threads[i], NULL);
    }

    MergedStation merged[1024];
    int merged_count = 0;

    for (int t = 0; t < num_threads; t++) {
        for (int i = 0; i < TABLE_SIZE; i++) {
            HashEntry *e = &tdata[t].table[i];
            if (e->count == 0) continue;

            uint8_t name_buf[36] = {0};
            _mm256_storeu_si256((__m256i *)name_buf, e->vec);

            int found = 0;
            for (int m = 0; m < merged_count; m++) {
                if (merged[m].len == e->len && memcmp(merged[m].name, name_buf, e->len) == 0) {
                    if (e->min < merged[m].min) merged[m].min = e->min;
                    if (e->max > merged[m].max) merged[m].max = e->max;
                    merged[m].sum += e->sum;
                    merged[m].count += e->count;
                    found = 1;
                    break;
                }
            }
            if (!found) {
                MergedStation *m = &merged[merged_count++];
                memcpy(m->name, name_buf, e->len);
                m->name[e->len] = '\0';
                m->len = e->len;
                m->min = e->min;
                m->max = e->max;
                m->sum = e->sum;
                m->count = e->count;
            }
        }
    }

    qsort(merged, merged_count, sizeof(MergedStation), compare_merged);

    // Build output buffer
    static char out_buf[128 * 1024];
    char *out_ptr = out_buf;
    *out_ptr++ = '{';

    for (int i = 0; i < merged_count; i++) {
        MergedStation *st = &merged[i];
        memcpy(out_ptr, st->name, st->len);
        out_ptr += st->len;
        *out_ptr++ = '=';

        out_ptr = format_fixed_1(out_ptr, st->min);
        *out_ptr++ = '/';

        double mean = (double)st->sum / (double)st->count / 10.0;
        double scaled = mean * 10.0;
        double r = (scaled >= 0) ? floor(scaled + 0.5) : ceil(scaled - 0.5);
        int mean_int = (int)r;
        if (mean_int == 0) mean_int = 0; // prevent -0.0
        out_ptr = format_fixed_1(out_ptr, mean_int);
        *out_ptr++ = '/';

        out_ptr = format_fixed_1(out_ptr, st->max);

        if (i + 1 < merged_count) {
            *out_ptr++ = ',';
            *out_ptr++ = ' ';
        }
    }

    *out_ptr++ = '}';
    *out_ptr++ = '\n';

    fwrite(out_buf, 1, out_ptr - out_buf, stdout);

    munmap((void *)data, file_size);
    close(fd);
    return 0;
}
